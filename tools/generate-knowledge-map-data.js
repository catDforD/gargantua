const fs = require("node:fs");
const path = require("node:path");
const yaml = require("js-yaml");

const root = path.resolve(__dirname, "..");
const nodesDir = path.join(root, "knowledge_map", "Nodes");
const output = path.join(root, "knowledge_map", "src", "data", "graph-data.ts");

const relationWeights = {
  prerequisites: 5,
  broader_than: 4,
  instantiates: 4,
  related: 2,
};

const categoryLabels = {
  agent: "Agent",
  engineering: "工程实践",
  frontend: "前端",
  backend: "后端",
  data: "数据",
  computer_science: "计算机科学",
};

const palette = ["#525252", "#737373", "#a3a3a3", "#b0b0b0", "#c4c4c4", "#d4d4d4"];

function parseNodeFile(fileName) {
  const filePath = path.join(nodesDir, fileName);
  const content = fs.readFileSync(filePath, "utf8");
  const match = content.match(/^---\s*\n([\s\S]*?)\n---\s*\n([\s\S]*)$/);
  if (!match) throw new Error(`${fileName}: missing YAML front matter`);

  const metadata = yaml.load(match[1]) || {};
  const body = match[2];
  const heading = body.match(/^#\s+(.+)$/m)?.[1]?.trim();
  const quote = body.match(/^>\s*(.+)$/m)?.[1]?.trim();
  const paragraph = body
    .replace(/^#.*$/gm, "")
    .split(/\n\s*\n/)
    .map((part) => part.replace(/\s+/g, " ").trim())
    .find((part) => part && !part.startsWith("- ") && !part.startsWith(">"));

  const id = String(metadata.id || `node:${path.basename(fileName, ".md")}`);
  const name = heading || path.basename(fileName, ".md");
  const categoryKey = String(metadata.domain || metadata.type || "other").toLowerCase();
  const relations = metadata.relations && typeof metadata.relations === "object" ? metadata.relations : {};

  return {
    id,
    name,
    aliases: Array.isArray(metadata.aliases) ? metadata.aliases.map(String) : [],
    category: categoryLabels[categoryKey] || categoryKey,
    description: quote || paragraph || "",
    relations,
    status: String(metadata.status || "active"),
  };
}

function normalize(value) {
  return String(value).trim().toLowerCase().replace(/\\/g, "/");
}

function relationTarget(value) {
  const raw = String(value).trim();
  const wiki = raw.match(/^\[\[([^\]]+)\]\]$/)?.[1] || raw;
  return wiki.split("#", 1)[0].split("/").pop().trim();
}

function unique(values) {
  return [...new Set(values)];
}

function buildGraph() {
  if (!fs.existsSync(nodesDir)) return { nodes: [], links: [], categories: [] };

  const files = fs.readdirSync(nodesDir).filter((file) => file.endsWith(".md")).sort();
  const parsed = files.map(parseNodeFile).filter((node) => !["inactive", "archived"].includes(node.status));
  const lookup = new Map();

  parsed.forEach((node) => {
    [node.id, node.name, ...node.aliases, node.id.replace(/^node:/, "")].forEach((key) => {
      lookup.set(normalize(key), node.id);
    });
  });

  const linkMap = new Map();
  const unresolved = [];
  parsed.forEach((node) => {
    Object.entries(node.relations).forEach(([kind, values]) => {
      if (!Array.isArray(values) || !relationWeights[kind]) return;
      values.forEach((value) => {
        const targetName = relationTarget(value);
        const target = lookup.get(normalize(targetName));
        if (!target) {
          unresolved.push(`${node.name} -> ${targetName}`);
          return;
        }
        if (target === node.id) return;
        const [source, destination] = [node.id, target].sort();
        const key = `${source}::${destination}`;
        const existing = linkMap.get(key);
        linkMap.set(key, {
          source,
          target: destination,
          weight: Math.max(existing?.weight || 0, relationWeights[kind]),
        });
      });
    });
  });

  if (unresolved.length) {
    console.warn(`Knowledge map: unresolved relations (${unresolved.length}):`);
    unresolved.forEach((item) => console.warn(`  - ${item}`));
  }

  const categories = unique(parsed.map((node) => node.category));
  const colors = categories.map((name, index) => ({ name, color: palette[index % palette.length] }));
  const nodes = parsed.map(({ id, name, category, description }) => ({ id, name, category, description }));
  const links = [...linkMap.values()].sort((a, b) => `${a.source}${a.target}`.localeCompare(`${b.source}${b.target}`));
  return { nodes, links, categories: colors };
}

const graph = buildGraph();
const outputText = `// Generated by tools/generate-knowledge-map-data.js. Do not edit manually.\n\nexport interface GraphNode {\n  id: string;\n  name: string;\n  category: string;\n  description: string;\n}\n\nexport interface GraphLink {\n  source: string;\n  target: string;\n  weight: number;\n}\n\nexport interface GraphData {\n  nodes: GraphNode[];\n  links: GraphLink[];\n}\n\nexport const CATEGORIES = ${JSON.stringify(graph.categories, null, 2)} as const;\n\nexport const graphData: GraphData = ${JSON.stringify({ nodes: graph.nodes, links: graph.links }, null, 2)};\n`;

fs.writeFileSync(output, outputText);
console.log(`Knowledge map: ${graph.nodes.length} nodes, ${graph.links.length} links`);
